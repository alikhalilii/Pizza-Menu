function Pizza({ pizzaObj }) {
  if (pizzaObj.soldOut) return null; //we can have multiple returns if we want an entirely different component to render under a condition

  return (
    <li className="pizza">
      <img src={pizzaObj.photoName} alt={pizzaObj.name} />
      <div>
        <h3>{pizzaObj.name}</h3>
        <p>{pizzaObj.ingredients}</p>
        <span>{pizzaObj.price}</span>
      </div>
    </li>
  );
}
